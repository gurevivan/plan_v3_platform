# -*- coding: utf-8 -*-
"""Роли: кто какой раздел плана может ПРАВИТЬ.

Два независимых измерения доступа, и их нельзя смешивать:

* **где** — ОП (площадка). Живёт в `UserOpAccess`, режется в QuerySet (ТЗ §7а).
* **что** — раздел плана. Живёт в группах Django, проверяется здесь.

Право на запись = И того, и другого: макропланировщик Бухары правит макроплан
и только по Бухаре. Заводить для этого третью таблицу не нужно — оба факта уже
хранятся по одному разу.

**Почему роли — это группы Django, а не своя таблица.** Пользователи, пароли и
группы у Django уже есть. Своя таблица ролей означала бы вторую запись того же
факта, и рано или поздно они разошлись бы — ровно так, как в самом приложении
разошлись экспорт и импорт и потеряли `orderLinks`.

**Почему нет роли «Администратор».** Признак администратора один — стандартный
`User.is_superuser`. Группа с тем же смыслом была бы вторым источником правды:
сняли галочку в одном месте, забыли в другом — и человек то ли админ, то ли нет.

**Почему ограничиваем только запись, а не чтение.** Аналитика считается на клиенте
по данным сервера, и ей нужны микроплан, макроплан, заказы и справочники сразу.
Запрет читать раздел сломал бы расчёт у того, кому аналитику как раз и открыли.
Чтение уже ограничено по ОП — этого достаточно: чужую площадку человек не увидит.
"""

# Раздел → (человеческое имя, basename'ы роутера, которые он закрывает).
# Имена разделов совпадают с ключами `SRV_TAB_KINDS` в «План.html»: один набор
# названий на сервер и на интерфейс, чтобы не сверять два списка глазами.
SECTIONS = {
    'refs': ('Справочники', (
        'nomenclature', 'ops', 'bases', 'delivery-matrix', 'holidays')),
    'contracts': ('Контракты и заказы', (
        'contracts', 'orders', 'order-links')),
    'macroplan': ('Макроплан', (
        'macroplan', 'macro-eff', 'time-costs')),
    'schedule': ('Графики бригад и ФРВ', (
        'schedules', 'schedule-month-overrides', 'cal-overrides', 'manual-frv')),
    'microplan': ('Микроплан', (
        'microplan', 'plan-baseline')),
}

# Роль (группа Django) → (описание, разделы на правку).
# Роль без разделов не нужна: «может только смотреть» — это отсутствие ролей,
# отдельная запись про это была бы тем же фактом во второй раз.
ROLES = {
    'Справочники': (
        'Ведёт номенклатуру, ОП и цеха, базы и матрицу доставок',
        ('refs',)),
    'Заказы': (
        'Ведёт контракты и заказы на производство',
        ('contracts',)),
    'Макропланирование': (
        'Заполняет макроплан и эффективность по месяцам',
        ('macroplan',)),
    'Микропланирование': (
        'Заполняет микроплан, графики бригад и ФРВ',
        ('microplan', 'schedule')),
}

#: путь роутера → раздел. Собирается из SECTIONS, вторым списком не задаётся.
SECTION_BY_PREFIX = {
    prefix: section
    for section, (_, prefixes) in SECTIONS.items()
    for prefix in prefixes
}


def sections_of(user):
    """Разделы, которые пользователь может править. `None` — все (администратор)."""
    if not user or not user.is_authenticated:
        return []
    if user.is_superuser:
        return None
    out = set()
    for name in user.groups.values_list('name', flat=True):
        role = ROLES.get(name)
        if role:
            out.update(role[1])
    return sorted(out)


def can_edit_section(user, section):
    """Может ли пользователь править раздел. Раздел `None` — сущность вне разделов."""
    if section is None:
        return True
    allowed = sections_of(user)
    return allowed is None or section in allowed


def group_for(name):
    """Группа Django под известную роль. Неизвестное имя — ошибка, а не новая роль.

    Роли создаются здесь по требованию, а не миграцией с данными: иначе список
    ролей лежал бы и в коде, и в миграции, и правку пришлось бы делать дважды.
    """
    from django.contrib.auth.models import Group

    if name not in ROLES:
        raise ValueError(f'неизвестная роль: {name}')
    group, _ = Group.objects.get_or_create(name=name)
    return group


def role_catalog():
    """Справочник ролей для интерфейса: что за роль и что она открывает."""
    return [{'name': name, 'description': descr,
             'sections': list(sections),
             'section_titles': [SECTIONS[s][0] for s in sections]}
            for name, (descr, sections) in ROLES.items()]
